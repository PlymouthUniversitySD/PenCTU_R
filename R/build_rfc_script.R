#' Make a study's copy of the reason-for-change JavaScript
#'
#' Builds the study's PenCTU_ReasonForChange.js from the validated script in the PenCTU package, with the
#' study's fields that never need a reason (from rfc_exempt_fields()) in its STUDY_EXEMPT_FIELDS setting,
#' and a header saying which study it is for, when it was made and from what. Nothing else in the script
#' is changed (the function checks this). Run it again whenever the data dictionary changes.
#'
#' @param metadata The study's data dictionary (as for rfc_exempt_fields()).
#' @param study_name Study name (letters, numbers, _ and -).
#' @param output_file Where to save the study's script, e.g. in the study's GitHub repository.
#' @param script Optional name and version of the script that ran this, for the header.
#' @param js_template The validated script; default the copy in the PenCTU package.
#' @return Invisibly, a list with the exempt fields and the file saved.
#' @export
build_rfc_script <- function(metadata, study_name, output_file, script = NULL,
                             js_template = system.file("js", "PenCTU_ReasonForChange.js", package = "PenCTU")) {
  version <- "1.0.0"
  if (length(study_name) != 1 || is.na(study_name) || !grepl("^[A-Za-z0-9_-]+$", study_name)) {
    stop("study_name must contain only letters, numbers, _ and -.")
  }
  if (!is.null(script) && (length(script) != 1 || is.na(script) || !is.character(script))) {
    stop("script must be a single piece of text, or left out.")
  }
  if (length(js_template) != 1 || js_template == "" || !file.exists(js_template)) {
    stop("The validated script PenCTU_ReasonForChange.js was not found (js_template). Update the PenCTU package.")
  }
  if (!dir.exists(dirname(output_file))) stop("The folder for output_file does not exist: ", dirname(output_file))
  printed <- utils::capture.output(fields <- rfc_exempt_fields(metadata))
  js <- readLines(js_template, encoding = "UTF-8", warn = FALSE)
  start <- grep("^\\s*const STUDY_EXEMPT_FIELDS = \\[", js)
  if (length(start) != 1) stop("The script does not have exactly one STUDY_EXEMPT_FIELDS setting.")
  end <- start - 1 + grep("\\];", js[start:length(js)])[1]
  ver <- regmatches(js, regexpr("V[0-9]+\\.[0-9]+\\.[0-9]+", js))[1]
  header <- c(paste0("// ", study_name, " copy of PenCTU_ReasonForChange.js ", ver, ", made ", format(Sys.time(), "%d %b %Y %H:%M"),
                     " by build_rfc_script V", version, if (!is.null(script)) paste0(" (", script, ")") else "", "."),
              paste0("// ", length(fields), " field(s) never need a reason (from the data dictionary). Do not edit this file by hand:"),
              "// run the template again after any change to the data dictionary or the script.")
  out <- c(header, js[seq_len(start - 1)], printed, js[(end + 1):length(js)])
  # check nothing but the setting changed
  if (!identical(out[-c(seq_along(header), length(header) + start)], js[-(start:end)])) {
    stop("Something other than the STUDY_EXEMPT_FIELDS setting would change - not saved.")
  }
  writeLines(enc2utf8(out), output_file, useBytes = TRUE)
  message("Saved ", output_file, " (", length(fields), " field(s) never need a reason). Copy it into the project's JavaScript Injector.")
  invisible(list(fields = fields, file = output_file))
}
